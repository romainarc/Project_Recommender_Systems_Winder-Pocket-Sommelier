export function makeT(lang) {
  const s = STRINGS[lang];
  const pick = (table, v) => (table[lang] && table[lang][v]) || v;
  return {
    ...s,
    lang,
    type: (v) => pick(TYPES, v),
    typeHint: (v) => pick(TYPE_HINTS, v),
    body: (v) => pick(BODY, v),
    bodyHint: (v) => pick(BODY_HINTS, v),
    acidity: (v) => pick(ACIDITY, v),
    acidityHint: (v) => pick(ACIDITY_HINTS, v),
    dish: (v) => pick(DISHES, v),
    dishLabel: (v) => (lang === "fr" ? DISH_LABELS_FR[v] || v : (v || "").toLowerCase()),
    country: (v) => (lang === "fr" ? COUNTRIES_FR[v] || v : v),
    bodyTitle: s.body,
    acidityTitle: s.acidity,
  };
}
